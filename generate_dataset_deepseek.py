def iter_rows(ds_like: Any, first_row: Dict[str, Any], limit: int) -> Iterable[Dict[str, Any]]:
    yield first_row
    count = 1
    for row in ds_like:
        if count >= limit:
            break
        yield row
        count += 1


def load_existing_ids(path: Path) -> set:
    ids = set()
    if not path.exists():
        return ids
    with path.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                ids.add(json.loads(line)["id"])
            except Exception:
                continue
    return ids



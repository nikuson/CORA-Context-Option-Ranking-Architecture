def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Генерация датасета для CORA через DeepSeek API: по умолчанию 2/3 чисто "
                    "текстовых сценариев (image_path=null, как в JEV) и 1/3 с картинками из "
                    "датасетов HuggingFace.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    p.add_argument("--out-dir", default="data", help="куда писать train.jsonl/val.jsonl/meta.jsonl")
    p.add_argument("--images-dir", default="images", help="подпапка для картинок (относительно --out-dir)")
    p.add_argument("--train-file", default="train.jsonl")
    p.add_argument("--val-file", default="val.jsonl")
    p.add_argument("--meta-file", default="meta.jsonl")

    p.add_argument("--sources", default="", help="список источников через запятую (см. --list-sources)")
    p.add_argument("--family", default="all", choices=["all", "computer_use", "real_world", "text"],
                   help="all = картинки (оба семейства) + текст; text = только текст; "
                        "computer_use/real_world = только соответствующие картинки")
    p.add_argument("--list-sources", action="store_true", help="показать источники картинок и выйти")
    p.add_argument("--total", type=int, default=DEFAULT_TOTAL,
                   help="суммарный бюджет примеров (используется, если не заданы --per-source/--text-per-domain)")
    p.add_argument("--image-share", type=float, default=DEFAULT_IMAGE_SHARE,
                   help="доля примеров с картинками; остальное — чистый текст (image_path=null). "
                        "0 = только текст, 1 = только картинки")
    p.add_argument("--per-source", type=int, default=0,
                   help="примеров на источник картинок (0 = автоматически из --total и --image-share)")
    p.add_argument("--oversample", type=float, default=1.6,
                   help="во сколько раз больше строк тянуть из HF (запас на брак/дубли)")
    p.add_argument("--limit", type=int, default=0, help="ограничить число строк на источник (0 = без лимита)")
    p.add_argument("--no-shuffle", action="store_true", help="не перемешивать стрим HF (быстрее старт)")

def generate_one_text(client: Optional[DeepSeekClient], dom: TextDomain, seed: str, angle: str,
                      detail: str, args: argparse.Namespace, dedupe: TextDedupe,
                      seen_lock: threading.Lock, rng: random.Random) -> GenResult:
    """Один чисто текстовый пример: image_path = null."""
    schema = dom.questions
    tag = f"text:{dom.key}"

    # ---- dry-run: без API, только проверка формата и пайплайна ----
    if args.dry_run or client is None:
        state_text = dry_text_state(dom, seed, angle, detail)
        with seen_lock:                      # в dry-run state_text — заглушка из затравки,
            dedupe.add(dedupe.signature(state_text))   # поэтому анти-повтор здесь не применяем
        ex_id = f"text_{dom.key}_{stable_hash(state_text)}"
        out_questions = [
            {"key": q.key, "text": q.text, "options": list(q.options or []),
             "target_probs": finalize_probs([1.0 / len(q.options)] * len(q.options))}
            for q in schema if q.options
        ]
        example = {"id": ex_id, "state_text": state_text, "image_path": None,
                   "questions": out_questions}
        meta = {"id": ex_id, "kind": "text", "source": tag, "domain": dom.key,
                "domain_title": dom.title, "seed": seed, "angle": angle, "detail": detail,
                "image": None, "teacher": None, "k": 0, "dry_run": True}
        return GenResult(example=example, meta=meta)

    # ---- фаза A: учитель придумывает ситуацию, факты и варианты ----
    msgs_a = build_text_phase_a_messages(dom, seed, angle, detail, schema, args.extra_questions,
                                         args.lang, args.min_facts)
    try:
        phase_a = parse_json_object(client.chat(msgs_a, temperature=args.temperature_a,
                                                max_tokens=args.max_tokens_a))
    except Exception as e:
        return GenResult(error=f"{tag}: фаза A: {type(e).__name__}: {e}")

    state_text = clamp_text(str(phase_a.get("state_text") or ""), MAX_STATE_CHARS)
    facts = [clamp_text(str(f), 300) for f in (phase_a.get("facts") or []) if str(f).strip()][:12]
    if len(state_text) < 60:
        return GenResult(error=f"{tag}: фаза A вернула слишком короткий state_text")
    if len(facts) < max(1, args.min_facts - 2):
        return GenResult(error=f"{tag}: в ситуации меньше твёрдых фактов, чем требуется "
                                f"({len(facts)} < {args.min_facts})")

    questions = resolve_questions(schema, phase_a)
    if not questions:
        return GenResult(error=f"{tag}: учитель не вернул ни одного валидного вопроса")
    justifications = {k: clamp_text(str(v.get("justification") or ""), 300)
                      for k, v in (phase_a.get("grounded_slots") or {}).items()
                      if isinstance(v, dict)}

    # ---- критик: логика, арифметика, достаточность фактов, реалистичность ----
    critic_ok, critic_issues, critic_answers = True, [], {}
    critic_used = False
    if args.critic:
        for attempt in range(1 + max(0, args.critic_retries)):
            teacher_answers = {q.key: q.gt_index for q in questions}
            msgs_c = build_critic_messages(state_text, facts, questions, teacher_answers)
            if attempt and critic_issues:
                msgs_c = msgs_c + [{"role": "user", "content":
                                    "ПРОБЛЕМЫ, НАЙДЕННЫЕ РЕЦЕНЗЕНТОМ (исправь ситуацию и верни "
                                    "JSON заново в формате фазы A):\n- " + "\n- ".join(critic_issues)}]
            try:
                verdict = parse_json_object(client.chat(
                    msgs_c, temperature=args.temperature_critic,
                    max_tokens=args.max_tokens_critic,
                    model=(args.critic_model or None)))
            except Exception as e:
                warn(f"{tag}: критик недоступен ({type(e).__name__}) — пример не проверяется")
                break
            critic_used = True
            critic_ok = bool(verdict.get("ok", False))
            critic_issues = [clamp_text(str(i), 240) for i in (verdict.get("issues") or [])][:5]
            fix = clamp_text(str(verdict.get("state_text_fix") or ""), MAX_STATE_CHARS)
            if fix and len(fix) >= 60:
                state_text = fix
            ba = verdict.get("best_answer") or {}
            critic_answers = {}
            for q in questions:
                v = ba.get(q.key)
                try:
                    iv = int(v) if v is not None else None
                except (TypeError, ValueError):
                    iv = None
                if iv is not None and 0 <= iv < len(q.options or []):
                    critic_answers[q.key] = iv
            if critic_ok:
                break
            if attempt >= args.critic_retries:
                return GenResult(error=f"{tag}: критик забраковал ситуацию: "
                                       + "; ".join(critic_issues or ["несогласованность"]))
            # ретрай: просим учителя переписать ситуацию с учётом замечаний
            try:
                phase_a = parse_json_object(client.chat(
                    msgs_a + [{"role": "assistant", "content": json.dumps(phase_a, ensure_ascii=False)},
                              {"role": "user", "content":
                               "Рецензент нашёл проблемы, перепиши ситуацию и верни тот же JSON:\n- "
                               + "\n- ".join(critic_issues)}],
                    temperature=args.temperature_a, max_tokens=args.max_tokens_a))
            except Exception as e:
                return GenResult(error=f"{tag}: ретрай после критика: {type(e).__name__}: {e}")
            state_text = clamp_text(str(phase_a.get("state_text") or state_text), MAX_STATE_CHARS)
            facts = [clamp_text(str(f), 300) for f in (phase_a.get("facts") or []) if str(f).strip()][:12]
            questions = resolve_questions(schema, phase_a) or questions

    # ---- анти-повтор ----
    sig = dedupe.signature(state_text)
    ex_id = f"text_{dom.key}_{stable_hash(state_text)}"
    with seen_lock:
        if dedupe.is_duplicate(sig):
            return GenResult(error=f"{tag}: state_text почти повторяет уже принятый пример")
        dedupe.add(sig)

    # ---- фаза B: self-consistency, K сэмплов вероятностей по зафиксированным вариантам ----
    msgs_b = build_phase_b_messages(state_text, questions,
                                    {"domain": dom.title, "role": dom.actor,
                                     "facts": "; ".join(facts)}, args.lang)
    votes: Dict[str, List[List[float]]] = {q.key: [] for q in questions}
    errors = 0
    for _ in range(max(1, args.k)):
        try:
            probs_obj = (parse_json_object(client.chat(
                msgs_b, temperature=args.temperature_b, max_tokens=args.max_tokens_b)) or {}).get("probs") or {}
        except Exception as e:
            errors += 1
            if args.verbose:
                warn(f"{tag}: фаза B: {type(e).__name__}: {e}")
            continue
        for q in questions:
            v = probs_obj.get(q.key)
            if isinstance(v, (list, tuple)) and len(v) == len(q.options or []):
                votes[q.key].append(normalize_probs([float(x) for x in v]))

    # мнение рецензента — один независимый голос ДОПОЛНИТЕЛЬНО к K сэмплам self-consistency
    critic_votes: Dict[str, List[float]] = {}
    if critic_used and critic_answers:
        for q in questions:
            idx = critic_answers.get(q.key)
            if idx is None:
                continue
            onehot = [0.0] * len(q.options or [])
            onehot[idx] = 1.0
            critic_votes[q.key] = onehot

    # ---- агрегация ----
    out_questions, agreement = [], {}
    used_gt_mix = 0.0
    for q in questions:
        n = len(q.options or [])
        vv = votes.get(q.key) or []
        all_votes = vv + ([critic_votes[q.key]] if q.key in critic_votes else [])
        gt_mix = args.text_gt_mix if (q.grounded and q.gt_index is not None) else 0.0
        used_gt_mix = max(used_gt_mix, gt_mix)
        p = aggregate_votes(all_votes, n, smoothing=args.label_smoothing,
                            gt_index=q.gt_index, gt_mix=gt_mix)
        if p is None:
            if errors >= args.k:
                p = finalize_probs([1.0 / n] * n)        # учитель совсем не отвечал
            else:
                continue                            # ни одного валидного голоса — вопрос выкидываем
        raw = aggregate_votes(vv, n, smoothing=0.0)      # чистая self-consistency, без априора
        agreement[q.key] = {"confidence": round(vote_confidence(p), 4),
                            "confidence_votes": round(vote_confidence(raw), 4) if raw else None,
                            "spread": round(vote_spread(vv), 4),
                            "n_votes": len(vv), "n_votes_with_critic": len(all_votes)}
        out_questions.append({"key": q.key, "text": q.text, "options": list(q.options),
                              "target_probs": p})

    if not out_questions:
        return GenResult(error=f"{tag}: не удалось собрать ни одного вопроса с вероятностями")

    # ---- фильтр «ситуация слишком размытая»: по главному вопросу нет перевеса.
    #      Считаем по ЧИСТЫМ K сэмплам self-consistency (без априора и голоса рецензента):
    #      если учитель при температуре не может выбрать вариант — факты не определяют ответ.
    primary = next((q.key for q in questions if q.grounded), out_questions[0]["key"])
    a_prim = agreement.get(primary, {})
    n_primary = len(next((q for q in out_questions if q["key"] == primary),
                         {"options": []})["options"]) or 1
    conf = a_prim.get("confidence_votes")
    if conf is None:                                 # все K сэмплов отвалились — смотрим на итог
        conf = a_prim.get("confidence", 0.0)
    if args.min_agreement > 0 and conf < max(args.min_agreement, 1.0 / n_primary + 0.05):
        return GenResult(error=f"{tag}: низкая self-consistency учителя по «{primary}» "
                               f"({conf:.2f} < {args.min_agreement}) — ситуация неоднозначна")

    example = {"id": ex_id, "state_text": state_text, "image_path": None,
               "questions": out_questions}
    meta = {
        "id": ex_id, "kind": "text", "source": tag, "domain": dom.key, "domain_title": dom.title,
        "seed": seed, "angle": angle, "detail": detail, "image": None, "image_md5": None,
        "teacher": client.model, "critic_model": args.critic_model or client.model,
        "critic_used": critic_used, "critic_ok": critic_ok, "critic_issues": critic_issues,
        "critic_answers": critic_answers, "facts": facts, "justifications": justifications,
        "k": args.k, "k_failed": errors, "label_smoothing": args.label_smoothing,
        "gt_mix": used_gt_mix, "agreement": agreement,
        "votes": {k: [[round(x, 5) for x in v] for v in vs] for k, vs in votes.items()},
    }
    return GenResult(example=example, meta=meta)



def run(args: argparse.Namespace) -> int:
    out_root = Path(args.out_dir).resolve()
    images_root = Path(args.images_dir) if os.path.isabs(args.images_dir) else out_root / args.images_dir
    out_root.mkdir(parents=True, exist_ok=True)

    api_key = args.api_key or os.environ.get("DEEPSEEK_API_KEY", "")
    if not args.dry_run and not api_key:
        raise SystemExit("нужен DEEPSEEK_API_KEY (или --api-key), либо запусти с --dry-run")
    if args.use_vision and not args.vision_model:
        raise SystemExit("--use-vision требует --vision-model <имя VL-модели на том же API>")

    client: Optional[DeepSeekClient] = None
    if not args.dry_run:
        client = DeepSeekClient(
            api_key=api_key, base_url=args.base_url, model=args.model,
            timeout=args.timeout, max_retries=args.max_retries,
            min_interval=(1.0 / args.rps) if args.rps > 0 else 0.0,
        )
        log(f"учитель: {args.model} @ {args.base_url}"
            + (f" | vision: {args.vision_model}" if args.use_vision else ""))

    sources = select_sources(args)
    domains = select_domains(args)
    per_source, text_per_domain, img_budget, txt_budget = plan_budget(args, len(sources), len(domains))
    img_left, txt_left = img_budget, txt_budget
    if sources:
        if Image is None:
            raise SystemExit("нужен пакет pillow: pip install pillow (для картиночной части)")
        if per_source <= 0:
            sources = []
        else:
            images_root.mkdir(parents=True, exist_ok=True)
    if not sources and not domains:
        raise SystemExit("нечего генерировать: проверь --family / --image-share / --total")

    log(f"КАРТИНКИ: источников {len(sources)} -> {[s.name for s in sources]}; "
        f"по {per_source} на источник, бюджет {img_budget}")
    log(f"ТЕКСТ: доменов {len(domains)}; по {text_per_domain} на домен, бюджет {txt_budget} "
        f"(целевая доля картинок {args.image_share:.2f})")

    rng = random.Random(args.seed)
    seen_hashes: set = set()
    seen_lock = threading.Lock()

    all_examples: List[Dict[str, Any]] = []
    all_meta: List[Dict[str, Any]] = []
    stats: Dict[str, Dict[str, int]] = {}

    done_ids = set()
    if args.resume:
        for p in (out_root / args.train_file, out_root / args.val_file):
            done_ids |= load_existing_ids(p)
        if done_ids:
            log(f"resume: уже сгенерировано {len(done_ids)} примеров — пропускаю их")

    for src in sources:
        cap = min(per_source, img_left)
        if cap <= 0:
            log("бюджет картинок выбран — остальные источники пропускаю")
            break
        t0 = time.time()
        stats[src.name] = {"ok": 0, "failed": 0}
        try:
            ds_like, first_row = load_stream(src, args.hf_token or os.environ.get("HF_TOKEN"),
                                             args.seed, shuffle=not args.no_shuffle)
        except Exception as e:
            msg = f"{src.name} ({src.hf_id}): {type(e).__name__}: {str(e)[:200]}"
            if src.optional:
                warn("пропускаю источник — " + msg)
                continue
            warn("НЕ удалось загрузить источник — " + msg)
            continue

        # тянем с запасом: часть строк отбракуется (дубликаты, битые картинки, ошибки API)
        fetch_limit = int(cap * args.oversample)
        tasks: List[Tuple[Source, Dict[str, Any]]] = []
        try:
            for row in iter_rows(ds_like, first_row, fetch_limit):
                tasks.append((src, row))
        except Exception as e:
            warn(f"{src.name}: стриминг оборвался на {len(tasks)} строках: {type(e).__name__}: {e}")

        if args.limit:
            tasks = tasks[: args.limit]
        log(f"{src.name}: загружено строк {len(tasks)} (за {time.time() - t0:.1f}s), генерирую...")

        results: List[GenResult] = []
        if args.workers <= 1:
            for s, row in tasks:
                results.append(generate_one(client, s, row, ds_like, args, images_root,
                                            out_root, seen_hashes, seen_lock, rng))
                if len([r for r in results if r.example]) >= cap:
                    break
        else:
            with ThreadPoolExecutor(max_workers=args.workers) as ex:
                futures = {ex.submit(generate_one, client, s, row, ds_like, args, images_root,
                                     out_root, seen_hashes, seen_lock, rng): s
                           for s, row in tasks}
                for fut in as_completed(futures):
                    try:
                        results.append(fut.result())
                    except Exception as e:
                        results.append(GenResult(error=f"{type(e).__name__}: {e}"))
                    if len([r for r in results if r.example]) >= cap:
                        for f in futures:
                            f.cancel()
                        break

        kept = 0
        for r in results:
            if r.example is None or r.example["id"] in done_ids or kept >= cap:
                stats[src.name]["failed"] += 1
                if r.error and args.verbose:
                    warn(r.error)
                continue
            all_examples.append(r.example)
            all_meta.append(r.meta or {})
            stats[src.name]["ok"] += 1
            kept += 1

        img_left -= stats[src.name]["ok"]
        log(f"{src.name}: готово {stats[src.name]['ok']}, отброшено {stats[src.name]['failed']} "
            f"({time.time() - t0:.1f}s)")


    # ==================================================================================
    # Текстовые сценарии (2/3 общей массы): учитель придумывает ситуацию сам,
    # рецензент её проверяет, K сэмплов дают мягкие вероятности. image_path = null.
    # ==================================================================================
    if domains and text_per_domain > 0:
        dedupe = TextDedupe(threshold=args.text_dedupe_threshold)
        domain_order = list(domains)
        rng.shuffle(domain_order)
        for dom in domain_order:
            cap_t = min(text_per_domain, txt_left)
            if cap_t <= 0:
                log("бюджет текстовых примеров выбран — остальные домены пропускаю")
                break
            t0 = time.time()
            key_stat = f"text:{dom.key}"
            exs, mts, kept, rejected = run_text_domain(client, dom, cap_t, args, dedupe,
                                                       seen_lock, rng, done_ids)
            all_examples.extend(exs)
            all_meta.extend(mts)
            stats[key_stat] = {"ok": kept, "failed": rejected}
            txt_left -= kept
            log(f"{key_stat}: готово {kept}, отброшено {rejected} ({time.time() - t0:.1f}s)")

    if not all_examples:
        warn("не сгенерировано ни одного примера — проверь доступ к HF и ключ API")
        return 1

    # ---- сплит train/val, стратифицированный по источнику/домену ----
    pairs = list(zip(all_examples, all_meta))
    rng.shuffle(pairs)
    by_source: Dict[str, List[Dict[str, Any]]] = {}
    for ex, meta in pairs:
        by_source.setdefault(meta.get("source", "unknown"), []).append(ex)
    train, val = [], []
    for name, items in by_source.items():
        rng.shuffle(items)
        n_train = max(1, int(round(len(items) * args.train_ratio))) if len(items) > 1 else len(items)
        train.extend(items[:n_train])
        val.extend(items[n_train:])
    if not val and len(train) > 1:             # на мелких стратах val может остаться пустым
        rng.shuffle(train)
        n_val = max(1, int(round(len(train) * (1.0 - args.train_ratio))))
        val, train = train[-n_val:], train[:-n_val]
    rng.shuffle(train)
    rng.shuffle(val)

    def write_jsonl(path: Path, items: Sequence[Dict[str, Any]], append: bool = False) -> None:
        mode = "a" if append else "w"
        with path.open(mode, encoding="utf-8") as f:
            for it in items:
                f.write(json.dumps(it, ensure_ascii=False) + "\n")

    train_path = out_root / args.train_file
    val_path = out_root / args.val_file
    write_jsonl(train_path, train, append=args.resume and bool(done_ids))
    write_jsonl(val_path, val, append=args.resume and bool(done_ids))

    meta_path = out_root / args.meta_file
    with meta_path.open("a" if (args.resume and done_ids) else "w", encoding="utf-8") as f:
        for m in all_meta:
            f.write(json.dumps(m, ensure_ascii=False) + "\n")

    n_text_ex = sum(1 for m in all_meta if m.get("kind") == "text")
    n_image_ex = len(all_meta) - n_text_ex
    share_actual = n_image_ex / max(1, len(all_meta))

    summary = {
        "generated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "teacher_model": args.model if client else None,
        "vision_model": args.vision_model if args.use_vision else None,
        "self_consistency_k": args.k,
        "label_smoothing": args.label_smoothing,
        "gt_mix": args.gt_mix,
        "lang": args.lang,
        "n_train": len(train), "n_val": len(val), "n_total": len(all_examples),
        "n_image": n_image_ex, "n_text": n_text_ex,
        "image_share_target": args.image_share, "image_share_actual": round(share_actual, 4),
        "text_share_actual": round(1.0 - share_actual, 4),
        "n_image_sources": len(sources), "n_text_domains": len(domains),
        "critic_enabled": bool(args.critic) and n_text_ex > 0,
        "critic_model": (args.critic_model or args.model) if args.critic else None,
        "min_facts": args.min_facts, "min_agreement": args.min_agreement,
        "text_gt_mix": args.text_gt_mix, "text_dedupe_threshold": args.text_dedupe_threshold,
        "per_source_stats": stats,
        "images_dir": os.path.relpath(images_root, out_root),
        "max_image_side": args.max_image_side,
    }
    if client:
        summary["api_calls"] = client.calls
        summary["prompt_tokens"] = client.tokens_in
        summary["completion_tokens"] = client.tokens_out
    (out_root / "generation_summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")

    log(f"готово: {train_path} ({len(train)}), {val_path} ({len(val)}), {meta_path}")
    log(f"состав: {n_image_ex} примеров с картинками + {n_text_ex} чисто текстовых "
        f"= {1.0 - share_actual:.0%} текста (цель была {1.0 - args.image_share:.0%})")
    if sources and abs(share_actual - args.image_share) > 0.10:
        warn("фактическая доля картинок отличается от целевой: часть источников могла "
             "отбраковаться. Подними --per-source/--total или уменьши --image-share.")
    if client:
        log(f"API: {client.calls} вызовов, {client.tokens_in} prompt / {client.tokens_out} completion токенов")
    log("Дальше: в ноутбуке укажи CFG['train_path']/CFG['val_path'] на эти файлы "
        "(image_path уже относительный к папке датасета).")
    return 0



def _risk_q(key: str = "risk_level", text: str = "Насколько высок риск в этой ситуации?") -> Question:
    return Question(key=key, text=text, options=["низкий", "средний", "высокий", "критический"])


def _yesno_q(key: str, text: str) -> Question:
    return Question(key=key, text=text, options=["да", "нет", "неясно из фактов"])


def _slot(key: str, text: str, n: int = 4, hint: str = "") -> Question:
    """Заземлённый слот: варианты придумывает учитель, он же заявляет верный индекс."""
    return Question(key=key, text=text, grounded=True, n_options=n, gt_hint=hint)



def plan_budget(args: argparse.Namespace, n_sources: int,
                n_domains: int) -> Tuple[int, int, int, int]:
    """Планирование объёма: (на источник картинок, на текстовый домен, бюджет картинок, бюджет текста).

    По умолчанию --image-share 1/3: треть датасета — сценарии с картинками из HF,
    две трети — чисто текстовые (image_path = null), как в текстовом JEV-пайплайне.
    Бюджеты нужны, чтобы ceil-округление «по доменам» не растягивало --total.
    """
    share = min(max(args.image_share, 0.0), 1.0)
    if args.per_source > 0 and args.text_per_domain > 0:      # оба заданы явно
        return (args.per_source, args.text_per_domain,
                args.per_source * n_sources, args.text_per_domain * n_domains)
    total = max(1, args.total)
    n_img = int(round(total * share)) if n_sources else 0
    n_txt = (total - n_img) if n_domains else 0
    per_source = args.per_source if args.per_source > 0 else (
        max(1, -(-n_img // n_sources)) if n_sources and n_img else 0)
    text_per_domain = args.text_per_domain if args.text_per_domain > 0 else (
        max(1, -(-n_txt // n_domains)) if n_domains and n_txt else 0)
    if args.per_source > 0:
        n_img = per_source * n_sources
    if args.text_per_domain > 0:
        n_txt = text_per_domain * n_domains
    return per_source, text_per_domain, n_img, n_txt


def run_text_domain(client: Optional[DeepSeekClient], dom: TextDomain, cap: int,
                    args: argparse.Namespace, dedupe: TextDedupe, seen_lock: threading.Lock,
                    rng: random.Random, done_ids: set) -> Tuple[List[Dict[str, Any]],
                                                                List[Dict[str, Any]], int, int]:
    """Набираем `cap` принятых примеров домена, при необходимости несколькими раундами.

    Часть ситуаций отбракуется (рецензент, анти-повтор, низкая уверенность учителя), поэтому:
      * задания берём БЕЗ повторов из всех комбинаций (затравка x угол x деталь обстановки) —
        это главный источник разнообразия выдуманных ситуаций;
      * если раунд не добрал, запускаем следующий (--text-rounds) на оставшееся количество.
    """
    combos = [(sd, an, dt) for sd in dom.seeds for an in TEXT_ANGLES for dt in TEXT_DETAILS]
    rng.shuffle(combos)
    pos, kept, rejected = 0, 0, 0
    examples: List[Dict[str, Any]] = []
    metas: List[Dict[str, Any]] = []

    for round_i in range(max(1, args.text_rounds)):
        need = cap - kept
        if need <= 0:
            break
        batch: List[Tuple[str, str, str]] = []
        for _ in range(max(1, int(round(need * args.text_oversample)))):
            if pos >= len(combos):                 # комбинации кончились — перемешиваем заново
                rng.shuffle(combos)
                pos = 0
            batch.append(combos[pos])
            pos += 1

        def accepted(res: List[GenResult]) -> int:
            return sum(1 for r in res if r.example and r.example["id"] not in done_ids)

        results: List[GenResult] = []
        if args.workers <= 1:
            for sd, an, dt in batch:
                results.append(generate_one_text(client, dom, sd, an, dt, args,
                                                 dedupe, seen_lock, rng))
                if accepted(results) >= need:
                    break
        else:
            with ThreadPoolExecutor(max_workers=args.workers) as ex:
                futs = [ex.submit(generate_one_text, client, dom, sd, an, dt, args,
                                  dedupe, seen_lock, rng) for sd, an, dt in batch]
                for fut in as_completed(futs):
                    try:
                        results.append(fut.result())
                    except Exception as e:
                        results.append(GenResult(error=f"{type(e).__name__}: {e}"))
                    if accepted(results) >= need:
                        for f in futs:
                            f.cancel()
                        break

        for r in results:
            if r.example is not None and r.example["id"] not in done_ids and kept < cap:
                examples.append(r.example)
                metas.append(r.meta or {})
                kept += 1
            else:
                rejected += 1
                if r.error and args.verbose:
                    warn(r.error)

        if kept < cap and round_i + 1 < args.text_rounds and args.verbose:
            warn(f"text:{dom.key}: раунд {round_i + 1} дал {kept}/{cap} — дозапускаю")

    if kept < cap:
        warn(f"text:{dom.key}: набралось {kept} из {cap} (брак от рецензента/дедупа/"
             f"низкой уверенности). Можно поднять --text-rounds, --text-oversample "
             f"или ослабить --min-agreement/--text-dedupe-threshold.")
    return examples, metas, kept, rejected


